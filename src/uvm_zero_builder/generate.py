"""Generate editable agent infrastructure, protocol skeletons, connection docs and a Makefile.

Normal generation creates missing files only. --refresh-infra deliberately replaces
agent/infra files, the connection document and the Makefile, never protocol implementations.
--check validates and previews all output without writing anything.
"""
import argparse
from importlib.resources import files as resources
from pathlib import Path
import re
from string import Template
import sys

from .plan import COMPONENTS, ConfigError, agent_class, agent_module, callbacks, interface_names, load_plan, module_for

_ATTRIBUTES = {"driver": "drivers", "monitor": "monitors", "scoreboard": "scoreboards", "stimulus": "stimuli"}


def _header(node, flag, class_name, config):
    return [f'"""{class_name}: the {flag} for {node.where}.', "",
            f"Generated by uvm_zero_builder.generate from {config}. Edit freely: this file is never",
            "overwritten. Replace each NotImplementedError with the protocol logic.", '"""']


def _init(state):
    return ["    def __init__(self, name, parent=None, **kwargs):",
            "        super().__init__(name, parent, **kwargs)", f"        # {state}"]


def _members(node, flag, class_name):
    """The interface keys a listed (or single) driver or monitor class uses."""
    return next(keys for _, value, keys in node.members(flag) if value == class_name)


def _interface_notes(node, keys):
    """Comments naming each interface's signals, clocks, resets and parameters; the code keeps no copies."""
    signals, parameters, tags = node.subtree_signals(), node.subtree_parameters(), node.subtree_tags()
    lines = []
    for key in keys:
        tagged = tags.get(key, {})
        plain = [name for name in signals[key] if name not in tagged]
        marks = "".join(f", {name} [{tag}]" for name, tag in tagged.items())
        lines.append(f"        # self.interfaces[{key!r}]: signals {', '.join(plain) or '(none)'}{marks}")
        if parameters.get(key):
            lines.append(f"        #     parameters (constants from the DUT): {', '.join(parameters[key])}")
    return lines


def _clock(node, key):
    """The interface's signal tagged [Clock], or None."""
    return next((name for name, tag in node.subtree_tags().get(key, {}).items() if tag == "Clock"), None)


def _transaction(node, key, class_name, fields, config):
    tags = node.tags.get(key, {})
    skipped = [f"Signals tagged [Clock] or [Reset] ({', '.join(tags)}) are not fields."] if tags else []
    return [f'"""{class_name}: one transfer on {node.where}\'s {key} interface.', "",
            f"Generated by uvm_zero_builder.generate from {config}. Edit freely: this file is never",
            f"overwritten. Each field is a signal of {key}, so a monitor builds one with",
            f"{class_name}.from_values(interface.values) and a driver writes one with",
            "drive_values(**txn.signal_values()).", *skipped, '"""',
            "from dataclasses import dataclass", "", "from uvm_zero_base import Transaction", "", "",
            "@dataclass", f"class {class_name}(Transaction):",
            *[f"    {name}: object = None" for name in fields],
            *([""] if fields else []),
            "    @classmethod",
            "    def idle_values(cls):",
            '        """Signal values while idle, such as during reset; the driver\'s drive_idle() writes them.',
            "",
            "        Remove any field the DUT drives (an output), and change values that are not idle at 0.",
            "        A single value covers every element of an array signal.",
            '        """',
            "        return {" + ", ".join(f"{name!r}: 0" for name in fields) + "}"]


def _txn(node, keys):
    """(import line, class name) of the Txn class for a component using exactly one interface."""
    if len(keys) != 1:
        return None
    owner, class_name = node.transaction_for(keys[0])
    return f"from {module_for('transaction', owner.plan, class_name)} import {class_name}", class_name


def _route_txn(route):
    """The Txn class a route delivers: its source monitor's or driver's, when that uses one interface.

    A scoreboard or stimulus may publish anything, so its targets' callbacks stay untyped.
    """
    if route.source_kind not in ("monitor", "driver"):
        return None
    keys = next(keys for key, _, keys in route.source_node.members(route.source_kind) if key == route.source_key)
    return _txn(route.source_node, keys)


def _imports(*groups):
    """Import lines in order, each once."""
    lines = []
    for group in groups:
        lines += [line for line in group if line not in lines]
    return lines


def _callback_methods(class_name, incoming, action):
    """(imports, lines): one on_<source>_callback per connection into this class, typed when known."""
    imports, lines = [], []
    for callback, route in incoming.items():
        typed = _route_txn(route)
        if typed and typed[0] not in imports:
            imports.append(typed[0])
        arguments = "".join(f"index_{level}, " for level in range(len(route.indices)))
        lines += ["", f"    def {callback}(self, {arguments}txn{': ' + typed[1] if typed else ''}):",
                  f'        """Items from {route.source_node.where}.{route.source_key}: "{route.source} -> {route.target}"."""',
                  f'        raise NotImplementedError("{class_name}.{callback}: {action}")']
    return imports, lines


def _publishes(outgoing):
    """A note naming where self.publish() delivers, for a class that is a connection source."""
    if not outgoing:
        return []
    return [f"        # self.publish(txn) delivers to: {', '.join(sorted(outgoing))}"]


def _which(keys, key):
    """The interface argument of drive_values(): only needed when there is a choice."""
    return "" if len(keys) == 1 else f"{key!r}, "


def _driver(node, class_name, config, incoming, outgoing):
    keys = _members(node, "driver", class_name)
    clock = _clock(node, keys[0])
    typed = _txn(node, keys)
    idle = {key: _txn(node, [key]) for key in keys}
    wait = [f"        #     await RisingEdge(self.interfaces[{keys[0]!r}].{clock})"] if clock else []
    callback_imports, callbacks = _callback_methods(class_name, incoming, "handle this transaction")
    imports = _imports([line for line, _ in idle.values()], callback_imports)
    return [*_header(node, "driver", class_name, config), "from uvm_zero_base import Driver", *imports, "", "",
            f"class {class_name}(Driver):", f'    """Drive transactions onto {node.where}."""', "",
            *_init("State kept between transactions goes here."), "",
            f"    async def drive(self, txn{': ' + typed[1] if typed else ''}):",
            '        """Drive one transaction; return once it has been driven.', "",
            "        Driver.run() takes each item from this driver's queue in the agent's handler",
            "        and calls drive() with it.",
            '        """',
            *_interface_notes(node, keys),
            "        # Wait for the protocol timing, then write the signals; drive_values() writes",
            "        # only those that differ from the live DUT value:",
            *wait,
            f"        #     self.drive_values({_which(keys, keys[0])}**txn.signal_values())",
            "        # self.interfaces[...].values is what the monitors observed: read it, never write it.",
            f'        raise NotImplementedError("{class_name}.drive: drive the transaction onto the signals")', "",
            "    def drive_idle(self):",
            '        """Called when reset asserts: write each interface\'s idle values, kept in its Txn class."""',
            *[f"        self.drive_values({_which(keys, key)}**{idle[key][1]}.idle_values())" for key in keys],
            *callbacks]


def _monitor(node, class_name, config, incoming, outgoing):
    # A listed monitor watches only its own interface.
    keys = _members(node, "monitor", class_name)
    names = interface_names(keys)
    clock = _clock(node, keys[0])
    txns = {key: _txn(node, [key]) for key in keys}
    valid = next((name for name in node.subtree_signals()[keys[0]] if name == "valid"), None)
    condition = [f"        #     if self.interfaces[{keys[0]!r}].values.{valid} == 1:"] if valid else []
    callback_imports, callbacks = _callback_methods(class_name, incoming, "handle this transaction")
    imports = _imports([line for line, _ in txns.values()], callback_imports)
    lines = [*_header(node, "monitor", class_name, config), "from uvm_zero_base import Monitor", *imports, "", "",
             f"class {class_name}(Monitor):", f'    """Observe {node.where} and publish protocol transfers."""', "",
             *_init("State kept between transfers goes here."), "", "    async def run(self):",
             '        """Decode transfers and publish them.', "",
             "        The base monitor keeps each interface's values current as its signals change,",
             "        and publish_<interface>() refreshes them before delivering.",
             '        """',
             *_interface_notes(node, keys),
             "        # Sample at the clock edge from the observed values, then publish; for example:",
             *([f"        #     await RisingEdge(self.interfaces[{keys[0]!r}].{clock})"] if clock else []),
             *condition,
             *[f"        #     {'    ' if condition else ''}self.publish_{name}("
               f"{txns[key][1]}.from_values(self.interfaces[{key!r}].values))" for key, name in names.items()],
             f'        raise NotImplementedError("{class_name}.run: observe transfers and publish them")']
    for key, name in names.items():
        lines += ["", f"    def publish_{name}(self, txn: {txns[key][1]}):",
                  f'        """Refresh {key}\'s values, then deliver to every connected component."""',
                  f"        self.publish(txn, interface={key!r})"]
    return lines + callbacks


def _scoreboard(node, class_name, config, incoming, outgoing):
    callback_imports, callbacks = _callback_methods(class_name, incoming, "check this transaction")
    return [*_header(node, "scoreboard", class_name, config), "from uvm_zero_base import Scoreboard",
            *callback_imports, "", "",
            f"class {class_name}(Scoreboard):",
            '    """Protocol matching and final checks belong here; the base supplies callbacks and heartbeat."""', "",
            *_init("Add only the queues, reference model and checks this protocol requires."),
            *_publishes(outgoing),
            *callbacks,
            "", "    def check_phase(self):", '        """Add protocol completion and pending-transaction checks if required."""',
            "        pass"]


def _stimulus(node, class_name, config, incoming, outgoing):
    # A driver of one interface takes that interface's Txn class; one spanning several takes Transaction.
    drivers, imports = [], []
    for prefix, child in node.subtree():
        for key, _, keys in child.members("driver"):
            typed = _txn(node, [prefix + interface for interface in keys])
            if typed:
                imports = _imports(imports, [typed[0]])
            drivers.append((prefix + key, typed[1] if typed else "Transaction"))
    others = [key for key, value, _ in node.members("stimulus") if value != class_name]
    interfaces = list(node.subtree_signals())
    base = "Stimulus, Transaction" if any(name == "Transaction" for _, name in drivers) else "Stimulus"
    callback_imports, callbacks = _callback_methods(class_name, incoming, "handle this transaction")
    return [*_header(node, "stimulus", class_name, config), f"from uvm_zero_base import {base}",
            *_imports(imports, callback_imports), "", "",
            f"class {class_name}(Stimulus):", f'    """A scenario registered with {node.where}."""', "",
            *_init("Scenario settings go here; TB_SEQUENCE_CONFIG can override them for a test."), "",
            "    async def run(self):",
            '        """Queue items for the drivers below, or run other registered stimuli."""',
            *[f'        # self.queue({name}(...), driver="{key}")' for key, name in drivers],
            *(["        # Add max_delay=N (or delay=N) to wait up to N clock cycles before it is driven."]
              if drivers else []),
            *[f'        # await self.agent.stimuli["{key}"].execute()' for key in others],
            *([f'        # Current interface status: self.handler.interfaces["{interfaces[0]}"].values.<signal>']
              if interfaces else []),
            "        # await self.wait_idle()",
            *_publishes(outgoing),
            f'        raise NotImplementedError("{class_name}.run: generate the scenario")',
            *callbacks]


def _agent_expression(prefix):
    return "self" + "".join(f".agents[{name!r}]" for name in prefix.rstrip(".").split(".") if name)


def _component_expression(prefix, kind, key):
    return f"{_agent_expression(prefix)}.{_ATTRIBUTES[kind]}[{key!r}]"


def _interface_expressions(node):
    return {prefix + key: f"{_agent_expression(prefix)}.interfaces[{key!r}]"
            for prefix, child in node.subtree() for key in child.interfaces}


def _connection(route):
    """The connect_callbacks() lines for one route: scoreboards keep their heartbeat wrapper."""
    source = _component_expression(route.source_prefix, route.source_kind, route.source_key)
    target = _component_expression(route.target_prefix, route.target_kind, route.target_key)
    lines = [f"        # {route.source} -> {route.target}"]
    if route.target_kind == "scoreboard":
        indices = f", indices={route.indices!r}" if route.indices else ""
        return lines + [f"        {target}.subscribe(", f"            {source}, {target}.{route.callback}{indices})"]

    method = f"{target}.{route.callback}"
    if route.indices:
        method = f"partial({method}, {', '.join(map(str, route.indices))})"
    return lines + [f"        {source}.add_callback(", f"            {method})"]


def _agent(node, directory, config_name):
    imports = [f"from {module_for(flag, node.plan, name)} import {name}" for flag, name in node.classes()]
    # Each component's class by key; a "true" flag selects the base class.
    members = {flag: {key: (value if isinstance(value, str) else flag.capitalize(), keys)
                      for key, value, keys in node.members(flag)} for flag in COMPONENTS}
    for child in node.children:
        imports.append(f"from {agent_module(child)} import {agent_class(child)}")

    routes = list(node.routes())
    if any(route.indices and route.target_kind != "scoreboard" for route in routes):
        imports.insert(0, "from functools import partial")

    construction = ["        interfaces = {"]
    for key, path in node.interfaces.items():
        relative = path.resolve().relative_to(directory.resolve()) if path.resolve().is_relative_to(directory.resolve()) else path.resolve()
        construction += [f"            {key!r}: Interface.from_json(parent.root.dut, config_dir / {str(relative)!r},",
                         "                                      connected_module=connected_module),"]
    construction = ["        interfaces = {}"] if not node.interfaces else [*construction, "        }"]
    construction += ["", "        super().__init__(",
                     "            name, parent,", f"            active={node.active!r}, interfaces=interfaces,",
                     *[f"            {flag}_types={{" + ", ".join(f"{key!r}: {name}" for key, (name, _) in members[flag].items()) + "},"
                       for flag in ("driver", "monitor", "scoreboard", "stimulus")],
                     "        )", "        self.connected_module = connected_module"]
    for child in node.children:
        binding = child.module_binding
        if binding is None:
            module = "connected_module"
        elif binding.startswith("."):
            module = f"connected_module + {binding!r}"
        else:
            module = repr(binding)
        construction += ["", f"        {agent_class(child)}({child.name!r}, self, config_dir=config_dir,",
                         f"                          connected_module={module})"]

    # Each driver and monitor sees the interfaces it uses: all below it, or its own when listed.
    bindings = _interface_expressions(node)
    for flag in ("driver", "monitor"):
        for key, (_, keys) in members[flag].items():
            construction += ["", f"        self.{flag}s[{key!r}].interfaces = {{",
                             *[f"            {interface!r}: {bindings[interface]}," for interface in keys], "        }"]

    connections = [line for route in routes for line in _connection(route)]
    if not connections:
        connections = ['        # No connections: add "<SourceClass> -> <TargetClass>" entries to the JSON.']

    # Import only the base classes this agent uses: Agent, Interface, and any "true" component.
    used = {name for flag in members for name, _ in members[flag].values()}
    base = ["Agent", *(["Interface"] if node.interfaces else []),
            *sorted(used & {"Driver", "Monitor", "Scoreboard", "Stimulus"})]
    template = Template(resources("uvm_zero_builder").joinpath("templates/agent.py.tmpl").read_text())
    return template.substitute(class_name=agent_class(node), agent_path=node.where, config_name=config_name,
                               base_imports=", ".join(base),
                               imports="\n".join(imports), module=repr(node.connected_module or "dut"),
                               construction="\n".join(construction), connections="\n".join(connections))


def _tests_of(tests, class_name):
    return [name for name, value in tests.items() if value == class_name]


def _member_lines(node, tests):
    lines = []
    for flag in COMPONENTS:
        for key, value, keys in node.members(flag):
            name = value if isinstance(value, str) else flag.capitalize()
            uses = (", using " + ", ".join(f"`{interface}`" for interface in keys)) if keys else ""
            runs = ""
            if flag == "stimulus":
                names = _tests_of(tests, value)
                runs = f", run by test {', '.join(names)}" if names else ", run by another stimulus"
            lines.append(f"- {flag.capitalize()} `{key}`: `{name}`{uses}{runs}")
    return lines


def _connection_lines(node, tests):
    lines = []
    for key, value, _ in node.members("stimulus"):
        names = _tests_of(tests, value)
        if names:
            lines.append(f"TbEnv (test {', '.join(names)}) -> stimuli['{key}'].execute()")
        for prefix, child in node.subtree():
            for driver, _, _ in child.members("driver"):
                lines.append(f"stimuli['{key}'].queue() -> {prefix}handler queue -> {prefix}{driver}")
    for key, _, keys in node.members("driver"):
        for interface in keys:
            lines.append(f"handler queue -> {key}.drive() -> {interface} signals -> DUT (writes only changes)")
    for key, _, keys in node.members("monitor"):
        for interface, name in interface_names(keys).items():
            lines.append(f"DUT -> {interface} signals -> {key}.publish_{name}() -> {interface}.values")
    for route in node.routes():
        via = " (scoreboard.callback: history, heartbeat)" if route.target_kind == "scoreboard" else ""
        indices = f" with indices {route.indices}" if route.indices else ""
        lines.append(f"{route.source_prefix}{route.source_key} ({route.source}) -> "
                     f"{route.target_prefix}{route.target_key}.{route.callback}{via}{indices}")
    return lines


_KINDS = {"driver": "drv", "monitor": "mon", "scoreboard": "sb", "stimulus": "st"}


def _node(*parts):
    """A Mermaid node id: "n_" plus word characters, never a Mermaid keyword such as end."""
    return "n_" + "_".join(re.sub(r"\W", "_", part) for part in parts if part)


def _agent_nodes(node, lines, indent):
    """One subgraph per agent: its handler, interfaces, components, and child agents."""
    lines.append(f'{indent}subgraph {_node("agent", node.where)}["{node.name} : {agent_class(node)}"]')
    inner = indent + "  "
    lines.append(f'{inner}{_node("handler", node.where)}[("handler")]')
    transactions = {key: class_name for key, class_name, _ in node.transactions()}
    for key in node.interfaces:
        lines.append(f'{inner}{_node("if", node.where, key)}[/"{key}<br/>{transactions[key]}"/]')
    for flag in COMPONENTS:
        for key, value, _ in node.members(flag):
            name = value if isinstance(value, str) else flag.capitalize()
            lines.append(f'{inner}{_node(_KINDS[flag], node.where, key)}["{key}<br/>{name}"]')
    for child in node.children:
        _agent_nodes(child, lines, inner)
    lines.append(f"{indent}end")


def _agent_edges(node, edges):
    """Data flow inside one agent, then its JSON connections."""
    for key, _, _ in node.members("stimulus"):
        stimulus = _node("st", node.where, key)
        for prefix, child in node.subtree():
            if any(True for _ in child.members("driver")):
                edges.add(f"{stimulus} -->|queue| {_node('handler', child.where)}")
    for key, _, keys in node.members("driver"):
        driver = _node("drv", node.where, key)
        edges.add(f"{_node('handler', node.where)} -->|pop| {driver}")
        for interface in keys:
            edges.add(f"{driver} -->|drive_values| {_node('if', node.where, interface)}")
    for key, _, keys in node.members("monitor"):
        for interface in keys:
            edges.add(f"{_node('if', node.where, interface)} -->|values| {_node('mon', node.where, key)}")
    for key in node.interfaces:
        edges.add(f"{_node('if', node.where, key)} <-->|signals| n_dut")
    for route in node.routes():
        source = _node(_KINDS[route.source_kind], route.source_node.where, route.source_key)
        target = _node(_KINDS[route.target_kind], route.target_node.where, route.target_key)
        edges.add(f"{source} -->|{route.callback}| {target}")
    for child in node.children:
        _agent_edges(child, edges)


def tb_diagram(plan):
    """A Mermaid flowchart of the testbench, built from the checked plan alone.

    GitHub and most Markdown viewers render it. Agents are boxes holding their
    handler, interfaces (parallelograms), and components; arrows show how items
    flow: stimulus -> handler queue -> driver -> interface -> DUT -> interface ->
    monitor -> connected components, labelled with the callback each one calls.
    """
    lines = ["flowchart LR", '  n_dut[["DUT"]]', '  subgraph n_tb_env["TbEnv"]']
    if plan.clock is not None:
        lines.append('    n_clock["clock<br/>ClockAgent"]')
    if plan.reset is not None:
        lines.append('    n_reset["reset<br/>ResetAgent"]')
    for top in plan.agents:
        _agent_nodes(top, lines, "    ")
    lines.append("  end")

    edges = set()
    for top in plan.agents:
        _agent_edges(top, edges)
    lines += [f"  {edge}" for edge in sorted(edges)]
    if plan.clock is not None:
        lines.append("  n_clock -->|clock| n_dut")
    if plan.reset is not None:
        lines.append("  n_reset -->|reset| n_dut")
        lines += [f"  n_reset -.->|resets| {_node('agent', top.where)}" for top in plan.agents]
    for name, class_name in plan.simulation["tests"].items():
        lines.append(f'  {_node("test", name)}(["test {name}"])')
        for top in plan.agents:
            for node in top.walk():
                for key, value, _ in node.members("stimulus"):
                    if value == class_name:
                        lines.append(f"  {_node('test', name)} -.->|runs| {_node('st', node.where, key)}")
    return "\n".join(lines) + "\n"


def connection_document(plan, config_name):
    tests = plan.simulation["tests"]
    lines = [f"# Testbench connections: {config_name}", "",
             "Generated from the JSON and agent template. If you edit agent/infra wiring manually, update this document too.",
             "", "## Diagram", "",
             "Agents are boxes; parallelograms are interfaces, labelled with their Txn class. Arrows follow",
             "the items: stimulus, handler queue, driver, interface, DUT, monitor, then each JSON connection,",
             "labelled with the callback it calls. Dotted arrows show tests and resets.", "",
             "```mermaid", *tb_diagram(plan).rstrip("\n").split("\n"), "```",
             "", "## Agent hierarchy", "", "- TbEnv"]
    for control in ("clock", "reset"):
        if getattr(plan, control) is not None:
            lines.append(f"  - {control} ({control.capitalize()}Agent)")
    for top in plan.agents:
        for node in top.walk():
            lines.append(f"{'  ' * len(node.path)}- {node.name} ({agent_class(node)})")
        if plan.reset is not None:
            lines.append(f"    - reset (passive ResetAgent, owned by {top.name})")
    lines += ["", "## Tests", ""]
    lines += [f"- `{name}` runs `{value}`" + (" (default)" if index == 0 else "")
              for index, (name, value) in enumerate(tests.items())] or ["- None: add simulation.tests to the config."]
    lines += ["", "## Components and connections by agent"]
    for top in plan.agents:
        for node in top.walk():
            lines += ["", f"### {node.where}", "", f"- Infrastructure: `{agent_module(node).replace('.', '/')}.py`",
                      f"- Connected module: `{node.connected_module or 'dut'}`",
                      "- Handler: `handler`, a queue per driver and every interface below"]
            transactions = {key: class_name for key, class_name, _ in node.transactions()}
            for key, path in node.interfaces.items():
                tagged = ", ".join(f"`{name}` [{tag}]" for name, tag in node.tags.get(key, {}).items())
                lines.append(f"- Interface: `{key}` from `{path.name}`; observed values in `{key}.values`; "
                             f"transaction `{transactions.get(key, '-')}`" + (f"; {tagged}" if tagged else ""))
            lines += _member_lines(node, tests)
            for child in node.children:
                lines.append(f"- Child agent: `{child.name}`")
            if node is top and plan.reset is not None:
                lines.append("- Child agent: `reset` (passive ResetAgent)")
            lines += ["", "#### Connections", "", "```text", *_connection_lines(node, tests), "```"]
    if plan.clock is not None:
        settings = plan.clock
        lines += ["", "### clock", "", "- Interface: `clock`",
                  f"- Monitor: `{'ClockMonitor' if settings['check_period'] else 'Monitor'}`"]
        if settings["active"]:
            lines.append("- Driver: `ClockDriver`")
        lines += ["", "#### Connections", "", "```text"]
        if settings["active"]:
            lines.append(f"ClockDriver -> clock -> {settings['signal']}")
        lines += [f"{settings['signal']} -> monitor -> clock.values",
                  "clock -> TbEnv heartbeat_clock", "```"]
    if plan.reset is not None:
        signal = plan.reset["signal"]
        for path, active in [("reset", True), *[(f"{top.where}.reset", False) for top in plan.agents]]:
            lines += ["", f"### {path}", "", "- Handler: `ResetHandler` (extends Handler)",
                      "- Interface: `reset`", "- Monitor: `ResetMonitor`"]
            if active:
                lines.append("- Driver: `ResetDriver`")
            lines += ["", "#### Connections", "", "```text"]
            if active:
                lines.append(f"ResetDriver -> reset -> {signal}")
            lines += [f"{signal} -> ResetMonitor -> reset.values", "ResetMonitor -> ResetHandler.observe_reset"]
            lines += ["ResetHandler.wait_released -> TbEnv test stimulus" if active else
                      "ResetMonitor -> parent.apply_reset / parent.release_reset", "```"]
    return "\n".join(lines) + "\n"


_RENDERERS = {"driver": _driver, "monitor": _monitor, "scoreboard": _scoreboard, "stimulus": _stimulus}


def _parameter_arguments(parameters):
    """Set DUT parameters at elaboration, like an RTL instantiation, for each simulator."""
    if not parameters:
        return ""

    def each(form):
        return " ".join(form.format(name=name, value=value) for name, value in parameters.items())

    return "\n".join([
        "# DUT parameters, set at elaboration like #(...) on an RTL instance. The testbench",
        "# reads the elaborated values back through each interface's \"parameters\".",
        "ifeq ($(SIM),icarus)",
        "COMPILE_ARGS += " + each("-P$(COCOTB_TOPLEVEL).{name}={value}"),
        "else ifeq ($(SIM),verilator)",
        "COMPILE_ARGS += " + each("-G{name}={value}"),
        "else ifneq ($(filter $(SIM),questa modelsim riviera activehdl),)",
        "SIM_ARGS += " + each("-g{name}={value}"),
        "else ifneq ($(filter $(SIM),xcelium ius),)",
        "EXTRA_ARGS += " + each("-defparam $(COCOTB_TOPLEVEL).{name}={value}"),
        "else ifeq ($(SIM),vcs)",
        "COMPILE_ARGS += " + each("-pvalue+$(COCOTB_TOPLEVEL).{name}={value}"),
        "endif", ""])


# Test names are read from the config whenever make runs, never copied into the Makefile.
_TEST_TARGETS = """
# One simulation per test, each with its own results file. The names come from
# simulation.tests in the config each time make runs, so adding or renaming a test
# needs no Makefile change. These follow the include, so "sim" stays the default goal.
TESTS := $(shell $(PYTHON) -c 'import json, sys; print(" ".join(json.load(open(sys.argv[1])).get("simulation", {}).get("tests", {})))' $(TB_CONFIG))
.PHONY: tests $(TESTS)
ifneq ($(strip $(TESTS)),)
$(TESTS):
\t$(MAKE) sim TB_TEST=$@ COCOTB_RESULTS_FILE=results_$@.xml
endif
tests:
\t@status=0; for test in $(TESTS); do \\
\t\t$(MAKE) sim TB_TEST=$$test COCOTB_RESULTS_FILE=results_$$test.xml || status=1; \\
\tdone; exit $$status
# cocotb's clean removes results.xml; the per-test results files are removed here.
clean::
\t@rm -f results_*.xml
"""


def _makefile(plan, config_name):
    """A Makefile next to the config that runs its tests."""
    settings = plan.simulation
    options = [*(["COMPILE_ARGS += " + " ".join(settings["compile_args"])] if settings["compile_args"] else []),
               *([_parameter_arguments(settings["parameters"]).rstrip("\n")] if settings["parameters"] else [])]
    template = Template(resources("uvm_zero_builder").joinpath("templates/Makefile.tmpl").read_text())
    return template.substitute(config_name=config_name, simulator=settings["simulator"],
                               toplevel=settings["toplevel"] or "",
                               sources=" ".join(f"$(CURDIR)/{source}" for source in settings["sources"]),
                               build_options="\n".join(options) + ("\n" if options else ""),
                               test_targets=_TEST_TARGETS)


def plan_files(plan, config_name):
    files = {}
    targets = callbacks(plan.agents)
    sources = {}
    for top in plan.agents:
        for node in top.walk():
            for route in node.routes():
                sources.setdefault((route.source_kind, route.source), set()).add(route.target)
    for top in plan.agents:
        for node in top.walk():
            for key, class_name, fields in node.transactions():
                path = Path(*module_for("transaction", node.plan, class_name).split(".")).with_suffix(".py")
                files.setdefault(path, "\n".join(_transaction(node, key, class_name, fields, config_name)) + "\n")
            for flag, class_name in node.classes():
                path = Path(*module_for(flag, node.plan, class_name).split(".")).with_suffix(".py")
                if path not in files:
                    incoming = targets.get((flag, class_name), {})
                    outgoing = sources.get((flag, class_name), set())
                    files[path] = "\n".join(_RENDERERS[flag](node, class_name, config_name, incoming, outgoing)) + "\n"
            files[Path(*agent_module(node).split(".")).with_suffix(".py")] = _agent(node, plan.directory, config_name)
    files[Path("tb_connections.md")] = connection_document(plan, config_name)
    files[Path("Makefile")] = _makefile(plan, config_name)
    return files


def unused_files(plan, files):
    directories = {plan.directory / path.parent for path in files if path.suffix == ".py"}
    directories |= {plan.directory / top.plan[0] / package for top in plan.agents for package in ("agent", "seqs", "agent/infra")}
    owned = {plan.directory / path for path in files}
    return sorted(path for directory in directories if directory.is_dir()
                  for path in directory.glob("*.py") if path not in owned)


def missing_callbacks(plan):
    """Yield (file, callback, route) for each connection an existing class does not handle yet."""
    for (kind, class_name), incoming in callbacks(plan.agents).items():
        route = next(iter(incoming.values()))
        path = plan.directory / Path(*module_for(kind, route.target_node.plan, class_name).split(".")).with_suffix(".py")
        if path.exists():
            source = path.read_text(encoding="utf-8")
            for callback, route in incoming.items():
                if f"def {callback}(" not in source:
                    yield path, callback, route


def main(argv=None):
    parser = argparse.ArgumentParser(prog="uvm-zero-generate", description=__doc__)
    parser.add_argument("config", help="the TB_CONFIG JSON file")
    parser.add_argument("--check", action="store_true", help="check and list the files without writing")
    parser.add_argument("--refresh-infra", action="store_true", help="replace agent/infra, the connection docs and the Makefile from templates; preserve protocol code")
    args = parser.parse_args(argv)
    config = Path(args.config)
    try:
        plan = load_plan(config)
        files = plan_files(plan, config.name)
        for path, source in files.items():
            if path.suffix == ".py":
                compile(source, str(path), "exec")
    except (ConfigError, SyntaxError) as error:
        print(f"check: {config} has problems:\n{error}", file=sys.stderr)
        return 1

    out = plan.directory
    writes = []
    for path in sorted(files):
        refresh = args.refresh_infra and ("infra" in path.parts or path.name in ("tb_connections.md", "Makefile"))
        status = "refresh" if refresh and (out / path).exists() else "exists" if (out / path).exists() else "missing"
        print(f"  {status:8} {out / path}")
        if status != "exists":
            writes.append((path, refresh))
    for path in unused_files(plan, files):
        print(f"  unused   {path} (not named by this configuration)")
    for path, callback, route in missing_callbacks(plan):
        print(f'  callback {path}: add def {callback}(...) for "{route.source} -> {route.target}"')
    if args.check:
        return 0

    for path, refresh in writes:
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "w" if refresh else "x", encoding="utf-8") as file:
            file.write(files[path])
        print(f"wrote    {target}")
    print("Existing protocol and infra files are preserved. After changing topology, review --check --refresh-infra, then use --refresh-infra to replace infra, docs and the Makefile.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
