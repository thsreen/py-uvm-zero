"""MatMulIpDriver: the driver for mat_mul.

Generated by uvm_zero_builder.generate from tb.json, then filled in: each item is one
A x B request, presented for one rising edge of clk with valid high.
"""
from cocotb.triggers import FallingEdge, RisingEdge

from uvm_zero_base import Driver
from mat_mul.agent.mat_mul_ip_txn import MatMulIpTxn


class MatMulIpDriver(Driver):
    """Drive transactions onto mat_mul."""

    def __init__(self, name, parent=None, **kwargs):
        super().__init__(name, parent, **kwargs)
        # State kept between transactions goes here.

    async def drive(self, txn: MatMulIpTxn):
        """Drive one transaction; return once it has been driven.

        Driver.run() takes each item from this driver's queue in the agent's handler
        and calls drive() with it.
        """
        # Change inputs on the falling edge, away from the rising edge that samples them.
        await FallingEdge(self.interfaces['ip'].clk)
        self.drive_values(**txn.signal_values())
        await RisingEdge(self.interfaces['ip'].clk)
        await FallingEdge(self.interfaces['ip'].clk)
        self.drive_values(valid=0)

    def drive_idle(self):
        """Called when reset asserts: set the outputs to their idle values."""
        self.drive_values(**MatMulIpTxn.idle_values())
