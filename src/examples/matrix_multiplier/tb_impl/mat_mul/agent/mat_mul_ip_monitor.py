"""MatMulIpMonitor: the monitor for mat_mul.

Generated by uvm_zero_builder.generate from tb.json, then filled in: publishes each
request the DUT accepts, that is valid high at a rising edge outside reset.
"""
from cocotb.triggers import RisingEdge

from uvm_zero_base import Monitor
from mat_mul.agent.mat_mul_ip_txn import MatMulIpTxn


class MatMulIpMonitor(Monitor):
    """Observe mat_mul and publish protocol transfers."""

    def __init__(self, name, parent=None, **kwargs):
        super().__init__(name, parent, **kwargs)
        # State kept between transfers goes here.

    async def run(self):
        """Decode transfers and publish them.

        The base monitor keeps each interface's values current as its signals change,
        and publish_<interface>() refreshes them before delivering.
        """
        # At the rising edge, values still hold what the DUT is about to sample.
        while True:
            await RisingEdge(self.interfaces['ip'].clk)
            if self.interfaces['ip'].values.valid == 1 and self.interfaces['ip'].values.reset == 0:
                self.publish_ip(MatMulIpTxn(valid=1,
                                            a=[int(word) for word in self.interfaces['ip'].values.a],
                                            b=[int(word) for word in self.interfaces['ip'].values.b]))

    def publish_ip(self, txn: MatMulIpTxn):
        """Refresh ip's values, then deliver to every connected component."""
        self.publish(txn, interface='ip')
