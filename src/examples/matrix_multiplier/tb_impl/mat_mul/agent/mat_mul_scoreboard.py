"""MatMulScoreboard: the scoreboard for mat_mul.

Generated by uvm_zero_builder.generate from tb.json, then filled in: a reference model
computes A x B for every accepted request, and each result must match the oldest one.
"""
from collections import deque

from uvm_zero_base import Scoreboard
from mat_mul.agent.mat_mul_ip_txn import MatMulIpTxn
from mat_mul.agent.mat_mul_op_txn import MatMulOpTxn


class MatMulScoreboard(Scoreboard):
    """Protocol matching and final checks belong here; the base supplies callbacks and heartbeat."""

    def __init__(self, name, parent=None, **kwargs):
        super().__init__(name, parent, **kwargs)
        self.expected = deque()
        self.checked = 0

    def on_ip_monitor_callback(self, txn: MatMulIpTxn):
        """Items from mat_mul.ip_monitor: "MatMulIpMonitor -> MatMulScoreboard"."""
        # The sizes come from the elaborated DUT, so a parameter override needs no change here.
        ip = self.parent.handler.interfaces["ip"]
        self.expected.append([sum(txn.a[row * ip.A_COLUMNS_B_ROWS + k] * txn.b[k * ip.B_COLUMNS + column]
                                  for k in range(ip.A_COLUMNS_B_ROWS))
                              for row in range(ip.A_ROWS) for column in range(ip.B_COLUMNS)])

    def on_op_monitor_callback(self, txn: MatMulOpTxn):
        """Items from mat_mul.op_monitor: "MatMulOpMonitor -> MatMulScoreboard"."""
        if not self.expected:
            self.error(f"result without a request: {txn.c}")
            return

        expected = self.expected.popleft()
        self.checked += 1
        if txn.c != expected:
            wrong = [index for index, (got, want) in enumerate(zip(txn.c, expected)) if got != want]
            self.error(f"result {self.checked}: elements {wrong} differ; got {txn.c}, expected {expected}")

    def check_phase(self):
        """Every accepted request must have produced its result."""
        if self.expected:
            self.error(f"{len(self.expected)} request(s) without a result")
        self.info(f"{self.checked} result(s) checked")

    def on_reset_asserted(self):
        # A reset discards requests still in the DUT.
        self.expected.clear()
