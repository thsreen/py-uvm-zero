"""MatMulTraffic: the stimulus for mat_mul.

Generated by uvm_zero_builder.generate from tb.json, then filled in: random A and B
matrices, sized from the DUT's parameters.
"""
from uvm_zero_base import Stimulus
from mat_mul.agent.mat_mul_ip_txn import MatMulIpTxn


class MatMulTraffic(Stimulus):
    """A scenario registered with mat_mul."""

    def __init__(self, name, parent=None, **kwargs):
        super().__init__(name, parent, **kwargs)
        # TB_SEQUENCE_CONFIG can override these for a test, e.g. {"count": 100, "max_delay": 0}.
        self.count = 20
        # Each request waits a random 0..max_delay clock cycles before it is driven.
        self.max_delay = 4

    async def run(self):
        """Queue items for the drivers below, or run other registered stimuli."""
        ip = self.handler.interfaces["ip"]
        largest = (1 << ip.DATA_WIDTH) - 1
        for _ in range(self.count):
            self.queue(MatMulIpTxn(valid=1,
                                   a=[self.random.randint(0, largest) for _ in range(ip.A_ROWS * ip.A_COLUMNS_B_ROWS)],
                                   b=[self.random.randint(0, largest) for _ in range(ip.A_COLUMNS_B_ROWS * ip.B_COLUMNS)]),
                       driver="ip_driver", max_delay=self.max_delay)
        await self.wait_idle()
